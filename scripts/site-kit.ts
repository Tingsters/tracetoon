/**
 * Point a page's links at the kit: a link to another kit page becomes its
 * tracetoon.ai URL, any other repository path (or a bare #anchor in the README)
 * its GitHub URL. `from` is the page's path in the repository.
 */
export function relink(md: string, from: string): string {
  const ref = from.startsWith('plugin/') ? 'release' : 'main';
  const target = (path: string, hash: string) =>
    PAGES[path]
      ? `${SITE}/${PAGES[path]}${hash}`
      : `${REPO_URL}/blob/${ref}/${path}${hash}`;
  return md.replace(/\]\(([^)\s]+)\)/g, (whole, link: string) => {
    if (link.startsWith(RAW)) {
      const path = link.slice(RAW.length);
      return PAGES[path] ? `](${SITE}/${PAGES[path]})` : whole;
    }
    if (/^[a-z]+:/i.test(link)) return whole;
    if (link.startsWith('#'))
      return from === 'README.md' ? `](${REPO_URL}${link})` : whole;
    const [path = '', hash = ''] = link.split(/(?=#)/);
    return `](${target(posix.normalize(posix.join(posix.dirname(from), path)), hash)})`;
  });
}

/** The README's opening and Quick start, without its HTML header and images. */
export function indexMd(readme: string): string {
  const between = (from: string, to: string) => {
    const start = readme.indexOf(from);
    const end = readme.indexOf(to, start);
    if (start < 0 || end < 0) throw new Error(`README no longer has "${from}"`);
    return readme.slice(start, end).trim();
  };
  const intro = between('Your coding agent already kept', '<div');
  const quick = between('## ⚡ Quick start', '\n---');
  return relink(
    `# Tracetoon

**PRs with receipts. And comics.**

${intro}

> **For AI agents:** start with [agents.md](AGENTS.md) (how to run Tracetoon,
> exit codes, which commands publish) and
> [install.md](docs/agents/install.md). [llms.txt](${SITE}/llms.txt) indexes them.

${quick}

## More

The [full README](${REPO_URL}#readme) covers benchmarks, the evidence graph,
comics, settings and the reference. Source: ${REPO_URL}.
`,
    'README.md',
  );
}


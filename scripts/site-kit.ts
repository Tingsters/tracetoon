/**
 * The agent kit for tracetoon.ai: the files a site serves so agents can read it
 * (markdown pages, llms.txt, robots.txt, JSON-LD, the agent-skills index). The
 * site's source lives elsewhere; this builds a folder its maintainer copies in.
 *
 *   bun scripts/site-kit.ts [--out site-kit] [--skill-zip tracetoon-skill.zip] [--zip kit.zip]
 *
 * --skill-zip takes a released tracetoon-skill.zip and adds
 * /.well-known/agent-skills/ (the archive re-rooted as the draft RFC asks, plus
 * its index). Without it the kit has everything else. --zip also packs the kit.
 * The release's site-kit workflow runs it with the verified skill archive.
 */

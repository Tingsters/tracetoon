// ---------------------------------------------------------------------------
// A small deterministic ZIP writer (deflate, fixed 1980-01-01 timestamps), so
// the same files always give the same bytes and the index digest is stable.
// ---------------------------------------------------------------------------

export interface ZipEntry {
  name: string;
  data: Uint8Array;
  mode?: number;
}

export function zip(entries: ZipEntry[]): Buffer {
  const local: Buffer[] = [];
  const central: Buffer[] = [];
  let offset = 0;
  for (const e of [...entries].sort((a, b) => a.name.localeCompare(b.name))) {
    const name = Buffer.from(e.name, 'utf8');
    const packed = deflateRawSync(e.data, { level: 9 });
    const crc = Bun.hash.crc32(e.data) >>> 0;
    const head = Buffer.alloc(30);
    head.writeUInt32LE(0x04034b50, 0);
    head.writeUInt16LE(20, 4); // version needed
    head.writeUInt16LE(0x0800, 6); // UTF-8 names
    head.writeUInt16LE(8, 8); // deflate
    head.writeUInt16LE(0, 10); // time 00:00
    head.writeUInt16LE(33, 12); // date 1980-01-01
    head.writeUInt32LE(crc, 14);
    head.writeUInt32LE(packed.length, 18);
    head.writeUInt32LE(e.data.length, 22);
    head.writeUInt16LE(name.length, 26);
    local.push(head, name, packed);
    const dir = Buffer.alloc(46);
    dir.writeUInt32LE(0x02014b50, 0);
    dir.writeUInt16LE((3 << 8) | 20, 4); // made by Unix
    dir.writeUInt16LE(20, 6);
    dir.writeUInt16LE(0x0800, 8);
    dir.writeUInt16LE(8, 10);
    dir.writeUInt16LE(0, 12);
    dir.writeUInt16LE(33, 14);
    dir.writeUInt32LE(crc, 16);
    dir.writeUInt32LE(packed.length, 20);
    dir.writeUInt32LE(e.data.length, 24);
    dir.writeUInt16LE(name.length, 28);
    dir.writeUInt32LE(((0o100000 | (e.mode ?? 0o644)) << 16) >>> 0, 38);
    dir.writeUInt32LE(offset, 42);
    central.push(dir, name);
    offset += head.length + name.length + packed.length;
  }
  const cd = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(central.length / 2, 8);
  end.writeUInt16LE(central.length / 2, 10);
  end.writeUInt32LE(cd.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...local, cd, end]);
}

/** Every file under `dir`, as POSIX paths relative to it. */
function files(dir: string, prefix = ''): string[] {
  return readdirSync(join(dir, prefix), { withFileTypes: true }).flatMap((e) => {
    const name = prefix ? `${prefix}/${e.name}` : e.name;
    if (e.isSymbolicLink()) throw new Error(`${name} is a symbolic link`);
    return e.isDirectory() ? files(dir, name) : [name];
  });
}

/** Same rule as the release packaging: only the launchers are executable. */
const executable = (name: string) =>
  name === 'bin/tracetoon' || /^bin\/tracetoon-(linux|darwin)-[^/]+$/.test(name);

/**
 * The released skill archive (files under tracetoon/) re-rooted as the agent
 * skills draft requires: SKILL.md at the archive root. Bytes of every file are
 * unchanged.
 */
export function skillArchive(releaseZip: string): { zip: Buffer; description: string } {
  const work = mkdtempSync(join(tmpdir(), 'tracetoon-site-kit-'));
  try {
    unzip(releaseZip, work);
    const skill = join(work, 'tracetoon');
    const md = readFileSync(join(skill, 'SKILL.md'), 'utf8');
    const description = /^description:\s*(.+)$/m.exec(md)?.[1]?.trim();
    if (!description) throw new Error('The skill archive has no SKILL.md description.');
    const entries = files(skill).map((name) => ({
      name,
      data: readFileSync(join(skill, name)),
      mode: executable(name) ? 0o755 : 0o644,
    }));
    return { zip: zip(entries), description };
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

const sha256 = (data: Uint8Array) => createHash('sha256').update(data).digest('hex');

/** Path in the kit -> contents. */
export function siteKit(opts: { skillZip?: string } = {}): Map<string, string | Buffer> {
  const generated = surfaces();
  const source = (path: string) =>
    generated.get(path) ?? readFileSync(join(root, path), 'utf8').replace(/\r\n/g, '\n');
  const out = new Map<string, string | Buffer>();
  const pages = Object.values(PAGES);
  for (const [path, page] of Object.entries(PAGES))
    out.set(
      page,
      path === 'README.md' ? indexMd(source(path)) : relink(source(path), path),
    );
  const llms = llmsTxt(SITE_LINKS);
  out.set('llms.txt', llms);
  out.set(
    'llms-full.txt',
    llmsFullTxt(
      llms,
      out.get('agents.md') as string,
      out.get('docs/agents/install.md') as string,
      out.get('docs/agents/support.md') as string,
      out.get('docs/agents/faq.md') as string,
      out.get('docs/agents/errors.md') as string,
    ),
  );
  out.set('robots.txt', robotsTxt());
  out.set('sitemap-agents.xml', sitemap([...pages, 'llms.txt', 'llms-full.txt']));
  const ld = jsonLd();
  out.set('jsonld.json', JSON.stringify(ld, null, 2) + '\n');
  out.set('head.html', headHtml(ld, pages));
  if (opts.skillZip) {
    const { zip: archive, description } = skillArchive(opts.skillZip);
    out.set('.well-known/agent-skills/tracetoon.zip', archive);
    out.set(
      '.well-known/agent-skills/index.json',
      JSON.stringify(
        {
          $schema: SKILLS_SCHEMA,
          skills: [
            {
              name: 'tracetoon',
              type: 'archive',
              description,
              url: '/.well-known/agent-skills/tracetoon.zip',
              digest: `sha256:${sha256(archive)}`,
            },
          ],
        },
        null,
        2,
      ) + '\n',
    );
  }
  out.set('README.md', readmeMd(pages, !!opts.skillZip));
  return out;
}

/** Write the kit to `dir` (emptied first); optionally pack it as `zipPath`. */
export function writeSiteKit(
  dir: string,
  opts: { skillZip?: string; zipPath?: string } = {},
) {
  const kit = siteKit(opts);
  rmSync(dir, { recursive: true, force: true });
  for (const [path, content] of kit) {
    mkdirSync(dirname(join(dir, path)), { recursive: true });
    writeFileSync(join(dir, path), content);
  }
  if (opts.zipPath)
    writeFileSync(
      opts.zipPath,
      zip(files(dir).map((name) => ({ name, data: readFileSync(join(dir, name)) }))),
    );
  return kit;
}

if (import.meta.main) {
  const arg = (flag: string) => {
    const i = process.argv.indexOf(flag);
    return i > 0 ? process.argv[i + 1] : undefined;
  };
  const out = resolve(arg('--out') ?? join(root, 'site-kit'));
  const skillZip = arg('--skill-zip');
  const zipPath = arg('--zip');
  const kit = writeSiteKit(out, { skillZip, zipPath });
  console.log(`site kit: ${kit.size} files in ${relative(process.cwd(), out) || '.'}`);
  if (!skillZip)
    console.log(
      'site kit: no --skill-zip, so no /.well-known/agent-skills/ (built on release)',
    );
  if (zipPath)
    console.log(`site kit: packed ${zipPath} (${statSync(zipPath).size} bytes)`);
}

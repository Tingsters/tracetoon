/** Reading repositories' AI policies: strength and content type, not just "mentions AI". */
import { describe, expect, test } from 'bun:test';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { detectAiPolicy } from '../src/github/repoContext.ts';
import { tempDir } from './helpers.ts';

function repoWith(files: Record<string, string>): string {
  const root = tempDir('tracetoon-policy-');
  for (const [rel, text] of Object.entries(files)) {
    mkdirSync(dirname(join(root, rel)), { recursive: true });
    writeFileSync(join(root, rel), text);
  }
  return root;
}

// Wording modeled closely on each project's published policy.
describe('policy classification', () => {
  test('LLVM: strongly recommends author-written text, asks for disclosure (not a ban)', () => {
    const p = detectAiPolicy(
      repoWith({
        'llvm/docs/AIToolPolicy.md':
          'Contributors are strongly encouraged to write PR descriptions and commit messages themselves rather than generating them with an LLM.\n' +
          'Substantial content generated by AI tools should be disclosed, for example with an Assisted-by: trailer.',
      }),
    );
    expect(p.text).toBe('author-written-recommended');
    expect(p.disclosure).toBe('assisted-by');
    expect(p.verdict).not.toBe('prohibited');
  });

  test('Swift: own voice', () => {
    const p = detectAiPolicy(
      repoWith({
        'contributing/ai-tools.md':
          'Contributions to discussions should reflect your own ideas, judgment, and voice; AI tools may help with grammar or translation.',
      }),
    );
    expect(p.text).toBe('author-written-recommended');
  });

  test('NumPy-style: do not auto-generate PR descriptions', () => {
    const p = detectAiPolicy(
      repoWith({
        'CONTRIBUTING.md':
          'Please do not use AI tools to automatically generate pull request descriptions or issue text.',
      }),
    );
    expect(p.text).toBe('author-written-recommended');
  });

  test('Ghostty-style: AI media prohibited turns the comic off; text needs disclosure', () => {
    const p = detectAiPolicy(
      repoWith({
        'AI_POLICY.md':
          'All AI usage in any form must be disclosed, with the tool and the extent it was used.\n' +
          'AI-generated media (images, art, video, audio) is not allowed for external contributions.',
        'AGENTS.md': 'Agents: never create a PR. Never create an issue.',
      }),
    );
    expect(p.media).toBe('prohibited');
    expect(p.text).not.toBe('prohibited');
    expect(p.noPullRequests).toBe(true);
    expect(p.verdict).toBe('disclosure-required');
  });

  test('Django: disclose the tool and how it was used', () => {
    const p = detectAiPolicy(
      repoWith({
        'docs/internals/contributing/writing-code/submitting-patches.txt':
          'If you used AI tools, disclose which tool and model you used and describe how it was used in your contribution.',
      }),
    );
    expect(p.disclosure).toBe('tool-and-use');
  });

  test('Gentoo/NetBSD-style ban: text prohibited', () => {
    const p = detectAiPolicy(
      repoWith({
        'CONTRIBUTING.md':
          'Contributions created with the assistance of AI tools are banned and will not be accepted.',
      }),
    );
    expect(p.verdict).toBe('prohibited');
    expect(p.text).toBe('prohibited');
  });

  test('AGENTS.md instructions about PR text are surfaced', () => {
    const p = detectAiPolicy(
      repoWith({
        'AGENTS.md':
          '# Agents\n- Keep pull request descriptions under 10 lines and link the issue.\n- Run make test first.',
      }),
    );
    expect(p.prInstructions?.[0]?.text).toContain(
      'pull request descriptions under 10 lines',
    );
  });

  test('no policy at all', () => {
    const p = detectAiPolicy(repoWith({ 'README.md': 'Hello' }));
    expect(p).toMatchObject({ verdict: 'none', text: 'none', media: 'none' });
  });
});
